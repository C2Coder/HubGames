#!/usr/bin/env python3
"""Rasterize the archived school SVG into a 288-byte blue/white emblem.
Requires Pillow and CairoSVG; runs only on the development machine.
"""
from io import BytesIO
from pathlib import Path
import xml.etree.ElementTree as ET
import cairosvg
from PIL import Image

root = Path(__file__).resolve().parents[1]
svg = ET.parse(root / 'main/assets/sps-trutnov.svg').getroot()
svg.set('viewBox', '0 0 28.8 28.8')
png = cairosvg.svg2png(bytestring=ET.tostring(svg), output_width=256, output_height=256)
im = Image.open(BytesIO(png)).convert('RGBA')
# Flatten transparent regions onto the single school blue; unify both SVG blues.
bg = Image.new('RGBA', im.size, (0, 138, 204, 255))
bg.alpha_composite(im)
im = bg.convert('RGB').resize((48, 48), Image.Resampling.LANCZOS)
bits = []
for y in range(48):
    for byte in range(6):
        value = 0
        for bit in range(8):
            r, g, b = im.getpixel((byte * 8 + bit, y))
            if r > 145 and g > 180 and b > 200:
                value |= 0x80 >> bit
        bits.append(value)
lines = [', '.join(f'0x{v:02x}' for v in bits[i:i+16]) for i in range(0, len(bits), 16)]
(root / 'main/assets/school_logo.h').write_text(
    '// Generated by tools/prepare_school_logo.py from the official school SVG.\n'
    '// Logo: Ludek Dusek, CC BY-SA 4.0; see main/assets/README.md.\n'
    '#pragma once\n#include <stdint.h>\n'
    'static const uint8_t school_logo[288] = {\n    ' + ',\n    '.join(lines) + '\n};\n')
